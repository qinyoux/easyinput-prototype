/// 获取字符串的拼音首字母串。
///
/// 中文字取拼音首字母（小写），非中文字符（英文、数字、符号）原样保留并转小写。
///
/// 示例：
/// - "微信" → "wx"
/// - "WeChat" → "wechat"
/// - "WPS Office" → "wps office"
/// - "剪映专业版" → "jyzyb"
pub fn initials_of(text: &str) -> String {
    text.chars()
        .map(|c| {
            if is_cjk(c) {
                initial_of(c)
            } else {
                c.to_ascii_lowercase()
            }
        })
        .collect()
}

/// 获取字符串的"单词首字母缩写"。
///
/// 规则：
/// - 中文：每个字取拼音首字母
/// - 英文：每个单词的首字母（以空格、连字符、下划线、斜杠分隔的算单词）
/// - 数字：忽略
///
/// 示例：
/// - "Visual Studio Code" → "vsc"
/// - "微信" → "wx"
/// - "WPS Office" → "wo"
/// - "网易云音乐" → "wyyyy"
pub fn abbrev_of(text: &str) -> String {
    let mut result = String::new();
    let mut prev_is_sep = true;

    for c in text.chars() {
        if is_cjk(c) {
            result.push(initial_of(c));
            prev_is_sep = false;
        } else if c.is_whitespace() || c == '-' || c == '_' || c == '/' || c == '\\' {
            prev_is_sep = true;
        } else if c.is_ascii_alphabetic() {
            if prev_is_sep {
                result.push(c.to_ascii_lowercase());
            }
            prev_is_sep = false;
        }
        // 数字和其他符号忽略
    }

    result
}

/// 判断字符是否为 CJK 统一表意文字（汉字）。
fn is_cjk(c: char) -> bool {
    let code = c as u32;
    (0x4E00..=0x9FFF).contains(&code)
}

